import { test, expect } from '@playwright/test';
import { parsePrice } from '../../utils/price.js';

// Юнит-тесты: браузер и интернет не нужны, выполняются за миллисекунды.
// Проверяют функцию, на которой держится проверка суммы в корзине.
test.describe('parsePrice', { tag: '@unit' }, () => {
  test('распознаёт цену в разных форматах', () => {
    // [текст на сайте, ожидаемое число]
    const cases = [
      ['$100', 100],
      ['49.99', 49.99],
      ['$1,299.00', 1299], // запятая = тысячи
      ['€1.299,00', 1299], // точка = тысячи
      ['1 299,50 грн', 1299.5],
      ['1,299', 1299],
      ['1,299,000', 1299000],
      ['0,99', 0.99],
    ];

    for (const [text, expected] of cases) {
      // Второй аргумент expect — подпись: при падении сразу видно, какой формат сломался
      expect(parsePrice(text), `цена "${text}"`).toBe(expected);
    }
  });

  test('бросает понятную ошибку, если в тексте нет цены', () => {
    expect(() => parsePrice('бесплатно')).toThrow(/Не удалось распознать цену/);
  });
});
